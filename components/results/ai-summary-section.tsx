import { ClipboardList, Clock, Code2, Lightbulb, Sparkles, TriangleAlert, Zap } from 'lucide-react'
import { Panel } from '@/components/ui/panel'
import type { AiSummary, RemediationRoadmap } from '@/types/report'

export function AiSummarySection({ ai }: { ai: AiSummary }) {
  if (!ai.available) {
    return (
      <Panel className="flex items-center gap-3 p-6">
        <span className="flex size-9 items-center justify-center border border-border bg-background/60 text-muted-foreground">
          <Sparkles className="size-4" />
        </span>
        <p className="text-sm text-muted-foreground">{ai.executive_summary}</p>
      </Panel>
    )
  }

  /*
   * Only claim an LLM wrote this when one actually did. When the deterministic
   * rule engine produced the text, present it as such — an "AI summary" badge
   * over machine-generated prose is exactly the kind of small overstatement
   * that erodes trust in the rest of the report.
   */
  const isLlm = !/rule engine|deterministic|fallback/i.test(ai.generated_by)
  const Icon = isLlm ? Sparkles : ClipboardList

  return (
    <Panel>
      <div className="flex items-center gap-2.5 border-b border-border/60 bg-primary/5 px-6 py-4">
        <span className="flex size-9 items-center justify-center bg-primary/15 text-primary">
          <Icon className="size-4" aria-hidden="true" />
        </span>
        <div>
          <h2 className="text-sm font-medium text-foreground">
            {isLlm ? 'AI executive summary' : 'Executive summary'}
          </h2>
          <p className="text-xs text-muted-foreground">
            {isLlm
              ? `Generated by ${ai.generated_by}`
              : `${ai.generated_by}, derived directly from scan evidence rather than an LLM`}
          </p>
        </div>
      </div>

      <div className="space-y-6 p-6">
        <p className="text-pretty leading-relaxed text-foreground/90">{ai.executive_summary}</p>

        {ai.technical_summary && (
          <div className="border border-border/60 bg-muted/40 p-4">
            <h3 className="flex items-center gap-2 text-sm font-medium text-foreground">
              <Code2 className="size-4 text-primary" />
              Technical analysis
            </h3>
            <p className="mt-2 text-pretty text-sm leading-relaxed text-muted-foreground">
              {ai.technical_summary}
            </p>
          </div>
        )}

        {ai.key_risks.length > 0 && (
          <div>
            <h3 className="flex items-center gap-2 text-sm font-medium text-foreground">
              <TriangleAlert className="size-4 text-severity-high" />
              Key risks
            </h3>
            <ul className="mt-3 space-y-2">
              {ai.key_risks.map((risk, i) => (
                <li key={i} className="flex gap-2.5 text-sm leading-relaxed text-muted-foreground">
                  <span className="mt-2 size-1.5 shrink-0 rounded-full bg-severity-high" />
                  {risk}
                </li>
              ))}
            </ul>
          </div>
        )}

        {ai.recommendations.length > 0 && (
          <div>
            <h3 className="flex items-center gap-2 text-sm font-medium text-foreground">
              <Lightbulb className="size-4 text-primary" />
              Recommendations
            </h3>
            <ol className="mt-3 space-y-2">
              {ai.recommendations.map((rec, i) => (
                <li key={i} className="flex gap-3 text-sm leading-relaxed text-muted-foreground">
                  <span className="font-mono text-xs text-primary">
                    {String(i + 1).padStart(2, '0')}
                  </span>
                  {rec}
                </li>
              ))}
            </ol>
          </div>
        )}

        <RemediationRoadmapBlock roadmap={ai.remediation} />
      </div>
    </Panel>
  )
}

const ROADMAP_PHASES = [
  {
    key: 'immediate' as const,
    label: 'Immediate',
    hint: 'Address now',
    icon: Zap,
    accent: 'text-severity-high',
    dot: 'bg-severity-high',
  },
  {
    key: 'short_term' as const,
    label: 'Short term',
    hint: 'Next few weeks',
    icon: Clock,
    accent: 'text-severity-medium',
    dot: 'bg-severity-medium',
  },
  {
    key: 'long_term' as const,
    label: 'Long term',
    hint: 'Ongoing posture',
    icon: Lightbulb,
    accent: 'text-primary',
    dot: 'bg-primary',
  },
]

function RemediationRoadmapBlock({ roadmap }: { roadmap?: RemediationRoadmap }) {
  const phases = ROADMAP_PHASES.filter((p) => (roadmap?.[p.key]?.length ?? 0) > 0)
  if (phases.length === 0) return null

  return (
    <div>
      <h3 className="text-sm font-medium text-foreground">Remediation roadmap</h3>
      <p className="mt-1 text-xs text-muted-foreground">
        Prioritized by urgency so you know what to tackle first.
      </p>
      <div className="mt-3 grid gap-3 sm:grid-cols-3">
        {phases.map((phase) => {
          const Icon = phase.icon
          const items = roadmap![phase.key]
          return (
            <div
              key={phase.key}
              data-report-card
              className="border border-border/60 bg-background/40 p-4"
            >
              <div className="flex items-center gap-2">
                <Icon className={`size-4 ${phase.accent}`} />
                <span className="text-sm font-medium text-foreground">{phase.label}</span>
              </div>
              <p className="mt-0.5 text-[11px] uppercase tracking-wide text-muted-foreground">
                {phase.hint}
              </p>
              <ul className="mt-3 space-y-2">
                {items.map((item, i) => (
                  <li key={i} className="flex gap-2 text-xs leading-relaxed text-muted-foreground">
                    <span className={`mt-1.5 size-1.5 shrink-0 rounded-full ${phase.dot}`} />
                    {item}
                  </li>
                ))}
              </ul>
            </div>
          )
        })}
      </div>
    </div>
  )
}
